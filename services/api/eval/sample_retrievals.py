"""Write real retrieval outputs (with citations) for a few hand-written queries over the benchmark corpus.

    PYTHONPATH=. python eval/sample_retrievals.py   ->  eval/results/sample_retrievals.md

Queries are written for this report (not FinanceBench text).  Output = the system's actual top results.
"""

from __future__ import annotations

import json
from pathlib import Path

from app.config import Settings
from app.indexing.store import ChunkStore
from app.indexing.vectors import close_clients
from app.qa.evidence import chunk_ref, route_documents
from app.retrieval.search import Retriever
from app.storage.db import Repository

HERE = Path(__file__).parent
QUERIES = [
    ("What was 3M's capital expenditure in fiscal 2018?", [("doc_3m_2018_10k", 60)]),
    ("AMD 2022 current assets, cash, short-term investments and current liabilities (quick ratio inputs)",
     [("doc_amd_2022_10k", 56)]),
    ("PepsiCo FY2022 restructuring charges in the income statement", [("doc_pepsico_2022_10k", 78)]),
    ("Revenue by segment chart for Fictional Example Holdings 2025", [("doc_synthetic_annual_report_excerpt", 3)]),
    ("What was Boeing's total revenue in FY2023?", []),
]


def main() -> None:
    s = Settings(data_dir=HERE / "data" / "corpus", embedder_model_path=HERE.parent / "models" / "all-MiniLM-L6-v2")
    repo, store = Repository(s.db_path), ChunkStore(s.db_path)
    docs = repo.list_documents()
    titles = {d["id"]: d["title"] for d in docs}
    r = Retriever(s, store=store)
    L = ["# Sample retrieval outputs (real system output, B4 = hybrid over layout chunks)", "",
         "Generated by `eval/sample_retrievals.py` over the benchmark corpus (PyMuPDF parse, MiniLM ONNX embedder). "
         "Document routing uses the company name in the query, as `/qa` does. Gold pages (where listed) were "
         "identified from FinanceBench evidence or the fixture generator.", ""]
    for q, gold in QUERIES:
        routed = [d["documentId"] for d in route_documents(q, docs)] or None
        res = r.search(q, method="hybrid", chunk_set="layout", document_ids=routed, k=3)
        rows = store.get(h.chunk_id for h in res.hits)
        L += [f"## {q}", "", f"Routed to: {', '.join(routed) if routed else 'whole corpus'} · effective method "
              f"`{res.effective_method}` · {res.timings_ms.get('total_ms', 0):.0f} ms"
              + (f" · gold: {', '.join(f'{d} p.{p}' for d, p in gold)}" if gold else " · no gold evidence exists (unanswerable)"), ""]
        for h in res.hits:
            c = chunk_ref(rows[h.chunk_id], titles)
            hit = any((c.document_id, p) in set(gold) for p in c.pages)
            reg = c.regions[0]
            excerpt = c.content.strip().replace("\n", " ⏎ ")[:420]
            L += [f"**#{h.rank}** `{c.kind}` · {c.document_id} · p.{c.pages[0]} · block `{reg.block_id}` · "
                  f"bbox ({reg.bbox.l:.0f}, {reg.bbox.t:.0f}, {reg.bbox.r:.0f}, {reg.bbox.b:.0f}) · "
                  f"section: {' › '.join(c.section_path[-2:]) or '—'} · ranks {json.dumps(h.method_ranks)}"
                  + (" · **gold page**" if hit else ""), "", f"> {excerpt}", ""]
    (HERE / "results" / "sample_retrievals.md").write_text("\n".join(L) + "\n")
    close_clients()
    print("\n".join(L))


if __name__ == "__main__":
    main()
