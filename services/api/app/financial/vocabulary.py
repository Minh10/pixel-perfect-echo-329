# derived metric -> (allowed final operations, required input metric groups: each group needs one member present)
DERIVED: dict[str, tuple[set[str], list[set[str]]]] = {
    "free_cash_flow": ({"subtract", "add", "sum"}, [{"operating_cash_flow"}, {"capital_expenditure"}]),
    "operating_margin": ({"percent_of", "divide"}, [{"operating_income"}, {"revenue"}]),
    "net_margin": ({"percent_of", "divide"}, [{"net_income"}, {"revenue"}]),
    "gross_margin": ({"percent_of", "divide"}, [{"gross_profit", "cost_of_sales"}, {"revenue"}]),
    "current_ratio": ({"divide"}, [{"current_assets"}, {"current_liabilities"}]),
    "quick_ratio": ({"divide"}, [{"cash"}, {"current_liabilities"}]),
    "capex_to_revenue": ({"percent_of", "divide"}, [{"capital_expenditure"}, {"revenue"}]),
    "growth": ({"percent_change"}, []),  # inputs: the same metric in two periods (checked separately)
}
DERIVED_PATTERNS: list[tuple[str, str]] = [
    ("free_cash_flow", r"free cash flow"),
    ("operating_margin", r"operating margin"),
    ("net_margin", r"(net|profit) margin"),
    ("gross_margin", r"gross margin"),
    ("current_ratio", r"current ratio"),
    ("quick_ratio", r"quick ratio|acid[- ]test"),
    ("capex_to_revenue", r"(capital expenditure|capex|capital spending|purchases of property).{0,60}"
                         r"(percentage|percent|%) of.{0,30}(revenue|net sales|sales)"),
    ("growth", r"\b(grow|growth|grew|percent(age)? change|change in percentage|by what percentage|% change)\b"),
]
DEFINITION_RE = re.compile(r"\b(defined as|calculated as|computed as|using|equal to|i\.e\.)\b", re.IGNORECASE)

_COMPILED = {k: [re.compile(rf"\b{p}\b", re.IGNORECASE) for p in v] for k, v in METRICS.items()}


def canonical_metrics(text: str) -> set[str]:
    """All canonical metrics named in text, preferring the longest match per span."""
    hits: list[tuple[int, int, str]] = []
    for name, pats in _COMPILED.items():
        for p in pats:
            for m in p.finditer(text):
                hits.append((m.start(), m.end(), name))
    hits.sort(key=lambda h: (-(h[1] - h[0]), h[0]))
    taken: list[tuple[int, int]] = []
    out: set[str] = set()
    for s, e, name in hits:
        if any(s < te and ts < e for ts, te in taken):
            continue
        taken.append((s, e))
        out.add(name)
    return out


def derived_metric(question: str) -> str | None:
    q = question.lower()
    for name, pat in DERIVED_PATTERNS:
        if re.search(pat, q):
            return name
    return None


def _stem(t: str) -> str:
    """Tiny inflection folding so 'increase' matches 'increased' and 'charges' matches 'charge'."""
    for suf in ("ies", "ing", "ed", "es", "s"):
        if len(t) > len(suf) + 3 and t.endswith(suf):
            return t[: -len(suf)] + ("y" if suf == "ies" else "")
    return t


def content_tokens(text: str) -> set[str]:
    stop = {"the", "of", "and", "for", "in", "on", "at", "to", "a", "an", "total", "year", "fiscal", "ended",
            "fy", "amount", "value", "reported", "company", "group", "consolidated"}
    out = set()
    for t in re.findall(r"[a-z][a-z&-]{1,}", text.lower()):
        if t not in stop:
            st = _stem(t)
            out.add(st[:-1] if st.endswith("e") and len(st) > 4 else st)  # increase/increased -> increas
    return out
